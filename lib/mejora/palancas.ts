/**
 * El catálogo de palancas (`referencia/CATALOGO_PALANCAS.md`).
 *
 * Cumple tres funciones: es el camino sin IA (hoy no hay `GEMINI_API_KEY`),
 * es el ancla que se le pasa a Gemini para que no invente, y es el reemplazo
 * cuando el validador de realismo descarta una propuesta.
 *
 * Las palancas que el documento trae con texto completo están transcritas
 * **literales** — ya están escritas en voz de producto. Las que el documento
 * deja en una línea (métrica, esfuerzo, inversión) están completadas siguiendo
 * sus seis reglas: medible con algo que ya tienen, ≤ 6 h/mes, dentro de su
 * control, rango de efecto honesto, con escalón siguiente, y sin motivación ni
 * signos de exclamación.
 *
 * Ninguna promete un número: prometen un rango típico y un método para medirlo.
 */

/** Condiciones del dossier que una palanca necesita para tener sentido. */
export type Requisito =
  | 'linea_base_energia'
  | 'presupuesto'
  | 'puede_cambiar_proveedores'
  | 'agua_relevante'
  | 'flota'
  | 'equipo_5'
  | 'local_propio'
  | 'espacio_fisico';

export interface Palanca {
  slug: string;
  /** Con `{{variables}}` que rellena `rellenarPlantilla`. */
  titulo_plantilla: string;
  dominio: DomainSlug;
  /** `'*'` = cualquier rubro. */
  rubros: string[];
  metrica: string;
  unidad: string;
  metrica_tipo: MetricaTipo;
  metodo_tipo: MetodoTipo;
  alcance: 1 | 2 | 3;
  /** Fracción, orientativa. 0 en las palancas de medición. */
  efecto_min: number;
  efecto_max: number;
  horizonte: Horizonte;
  ambicion: Ambicion;
  esfuerzo_horas_mes: number;
  inversion: Inversion;
  requiere: Requisito[];
  /** Frases que, si aparecen en "ya hecho", significan que esto ya está hecho. */
  claves: string[];
  porque: string;
  pasos: string[];
  como_medir: string;
  evidencia_requerida: string;
  si_no_llegas: string;
  confianza: Confianza;
  es_evento_unico?: boolean;
  escalon_siguiente?: string;
}

