export function palanca(slug: string | null | undefined): Palanca | undefined {
  return slug ? PALANCAS.find((p) => p.slug === slug) : undefined;
}

/** Las palancas de un rubro: las suyas y las transversales. */
export function palancasPara(rubro: string, tamano?: string): Palanca[] {
  return PALANCAS.filter((p) => p.rubros.includes('*') || p.rubros.includes(rubro)).filter((p) => {
    // `movilidad-equipo` no tiene sentido con dos personas.
    if (p.requiere.includes('equipo_5') && tamano === '1') return false;
    return true;
  });
}

/** Si el dossier cumple lo que la palanca necesita para tener sentido. */
export function cumpleRequisitos(p: Palanca, d: Dossier): boolean {
  for (const r of p.requiere) {
    if (r === 'presupuesto' && d.restricciones.presupuesto === 'ninguno') return false;
    if (r === 'linea_base_energia' && !(typeof d.energia.consumo_mensual === 'number' || d.energia.tiene_factura === true))
      return false;
    if (r === 'puede_cambiar_proveedores' && d.insumos.puede_cambiar_proveedores === false) return false;
    if (r === 'agua_relevante' && d.agua.es_relevante === false) return false;
    if (r === 'flota' && (d.logistica.flota === 'no_aplica' || d.logistica.flota === 'retiran')) return false;
    if (r === 'local_propio' && d.restricciones.local === 'alquilado') return false;
  }
  if (p.esfuerzo_horas_mes > d.restricciones.horas_mes_disponibles) return false;
  return true;
}

